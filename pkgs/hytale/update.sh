#!/usr/bin/env nix-shell
#!nix-shell -i bash -p curl jq nix

set -euo pipefail

API_URL="https://launcher.hytale.com/version/release/launcher.json"
PACKAGE_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "Fetching latest Hytale Launcher metadata..."

api_data="$(curl --retry 5 --retry-delay 2 --retry-all-errors --connect-timeout 10 -fsSL "$API_URL")"

version="$(jq -r '.version // ""' <<<"$api_data")"
zip_sha="$(jq -r '.download_url.linux.amd64.sha256 // ""' <<<"$api_data")"

if [ -z "$version" ] || [ -z "$zip_sha" ]; then
  echo "Error: incomplete metadata returned by the API" >&2
  exit 1
fi

echo "Latest version: $version"

# The API publishes the SHA-256 (base16) of the ZIP; convert it to the SRI
# format expected by fetchurl without re-downloading the archive.
sri_hash="$(nix hash convert --hash-algo sha256 --from base16 --to sri "$zip_sha")"

cat >"$PACKAGE_DIR/source.nix" <<EOF
# Auto-generated by update.sh - do not edit manually
{
  version = "$version";
  sha256 = "$sri_hash";
}
EOF

echo "Updated $PACKAGE_DIR/source.nix"
echo "  version = $version"
echo "  sha256  = $sri_hash"
echo "Rebuild your system with the new version"
